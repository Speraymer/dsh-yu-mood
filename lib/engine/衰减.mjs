// 衰减 —— 没人跟她说话的钟头里，她自己慢慢回到平常。
//
// 两条曲线都是指数式：每一步挪掉"还差的量"的一个比例，
// 比例 = 1 - exp(-ln2 × 过去多少 / 半衰)，所以"过一个半衰恰好走一半"。
//
// 为什么不是每轮减一个固定数：固定步长要么抹平一切（几轮就归零），
// 要么在长夜里一动不动 —— 人不是那样回稳的，越接近平常走得越慢才像活人。
//
// ⚠️ 一个坑：不能拿"跟上次调用比"来判断走了多远。面板 20 秒轮询一次，
//    单次只挪零点几格，永远攒不够一条记录。只能跟"上次记过的那条"比。

import { 夹紧, 平复够格, 情绪半衰分钟, 情绪 } from './量表.mjs'
import { 共用房间, 房间, 记一条, 读状态, 存状态 } from './状态.mjs'

const 一分钟 = 60000

/**
 * 自然平复本身也是一次"变化"，得留一条记录。
 *
 * 以前衰减是悄悄算的：隔了一夜心情自己回到基线，时间线里一条都没有，
 * 于是下次开口她看到的还是昨天那句「刚才……」，时间对不上，还显得记仇。
 *
 * 这句理由写的是"过去了几个钟头"，不是哪个房间里发生过什么，
 * 所以记进共用房间 —— 谁读到都不算串味。
 */
function 记平复(s, { 现在, 诊断 }) {
  // 心情在往下走的路上是自己散的；已经在上面是"别扭过去了、人松快了"
  const 往回落 = s.mood < s.lastNotedMood
  const 理由 = 往回落
    ? '时间过去了一阵，先前那股劲儿慢慢淡了，心里回到平常的样子'
    : '时间过去了一阵，心里那点别扭自己散了，人也松快回来'

  // 本地算的，不是模型猜的 —— 可信度给满，这次一定说得出口
  记一条(房间(s, 共用房间), {
    at: 现在,
    mood: s.mood,
    delta: 0,
    reason: 理由,
    conf: 100,
    kind: 'decay',
    小波动: false,
    dims: s.dims,
    dimsDelta: {},
    房间键: 共用房间,
  })
  s.lastNotedMood = s.mood
  诊断('自然平复：mood=' + s.mood + '（' + 理由 + '）')
}

/**
 * 让账本随时间走一步。**原地改** s，返回它（调用方决定存不存盘）。
 *
 * @param s     账本
 * @param 基线   心情往这个数回落
 * @param 现在   毫秒
 * @param 半衰小时 心情走掉一半要多久（1~168 小时，默认 12）
 * @param 诊断   写日志
 */
export function 平复(s, { 基线 = 70, 现在 = Date.now(), 半衰小时 = 12, 诊断 = () => {} } = {}) {
  const 过去分钟 = Math.max(0, 现在 - (Number(s.lastDecayAt) || 0)) / 一分钟
  if (过去分钟 < 1) return s // 不到一分钟，四舍五入都是原地不动

  const 半衰分钟 = 夹紧(Number(半衰小时) || 12, 1, 168) * 60

  // 心情：朝着基线走，越近越慢
  const 心情进度 = 1 - Math.exp(-(Math.LN2 * 过去分钟) / 半衰分钟)
  s.mood = Math.round(s.mood + (基线 - s.mood) * 心情进度)

  // 七根情绪：朝着 0 走，散得比总分快（90 分钟半衰）
  const 情绪进度 = 1 - Math.exp(-(Math.LN2 * 过去分钟) / 情绪半衰分钟)
  for (const x of 情绪) s.dims[x.键] = Math.max(0, Math.round(s.dims[x.键] * (1 - 情绪进度)))

  s.lastDecayAt = 现在

  // 跟"上次记过的那条"比：走了够格就记一条
  if (Math.abs(s.mood - s.lastNotedMood) >= 平复够格) 记平复(s, { 现在, 诊断 })
  return s
}

/**
 * 读最新的账本（先走一步时间），要的话顺手存盘。
 * 面板、注入、判断前都走这个口子 —— 免得每一处各写一遍"读 + 平复"。
 */
export function 取最新({ 状态路径, 基线 = 70, 半衰小时 = 12, 存 = false, 老账落哪 = 共用房间, 诊断 = () => {} }) {
  const s = 读状态(状态路径, { 老账落哪 })
  平复(s, { 基线, 现在: Date.now(), 半衰小时, 诊断 })
  if (存) 存状态(状态路径, s)
  return s
}
