// 四、落账 / 够不够显眼
// --------------------------------------------------------------------------

/**
 * 把增量写进账本（原地改 s）。
 *
 * 心情是"基调"，走得慢：判定给的涨跌先除以 3 才落一格，几轮聊下来才挪一点点；
 * 七根情绪才是即时的，每轮都该动。时间线里记的是**实际挪了几格**，跟面板上的数对得上。
 *
 * @returns 心情这次实际挪了几格
 */
export function 落账(s, 增量, { 下限 = 0, 小波动 = false, 房间键 = '', 现在 = Date.now() } = {}) {
  const 步 = Math.round(增量.moodDelta / 心情每格)
  s.mood = 夹紧(Math.round(s.mood + 步), 下限, 100)
  for (const x of 情绪) s.dims[x.键] = 夹紧(Math.round(s.dims[x.键] + 增量.dims[x.键]), 0, 100)
  s.lastNotedMood = s.mood
  s.updatedAt = 现在
  s.lastDecayAt = 现在 // 刚变过，平复的计时归零

  // 理由只写进"说话的这个房间" —— 理由里带着那轮的原话
  记一条(房间(s, 房间键), {
    at: 现在,
    mood: s.mood,
    delta: 步,
    reason: 增量.reason,
    conf: 增量.confidence,
    kind: '',
    小波动: Boolean(小波动),
    dims: s.dims,
    dimsDelta: 增量.dims,
    房间键,
  })
  return 步
}

/**
 * 这次变化算不算"够显眼"：心情涨跌够数，或者某一根情绪涨跌够数。
 * 够不着就只记账、不进她的嘴 —— 以前任何一根动一点就算，一天能记四十条，
 * 那才是"被心情污染"的真正来源。
 */
export function 够显眼(增量, { sigMood = 3, sigDim = 5 } = {}) {
  if (Math.abs(增量.moodDelta) >= sigMood) return true
  return 情绪.some((x) => Math.abs(Number(增量.dims[x.键]) || 0) >= sigDim)
}

/** 这一轮有没有真的动过（一点都没动就不必记时间线）。 */
export function 有波动(增量) {
  if (Math.round(增量.moodDelta / 心情每格) !== 0) return true
  return 情绪.some((x) => Number(增量.dims[x.键]) !== 0)
}
