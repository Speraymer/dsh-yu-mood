// 判定 —— 每轮聊完，问一次模型「你刚才心里动了多少」，再把答复折成账本上的数。
//
// 三件事：
//   1. 拼提示词（怎么看这一轮）—— 规则都在下面，一条都不是装饰，每条都对应一次踩过的坑；
//   2. 解析回包（模型只该给一个 JSON，但实际会裹代码块、会截断、会漏字段）；
//   3. 落账（判定值 ÷3 变成心情的步子、七根情绪即时加、时间线追一条）。
//
// ⚠️ 为什么不用 @deepseek-ai/dsh-llm 造消息：本插件用 link: 装，DSH 从真实路径 import，
//    而 @deepseek-ai/* 只挂在 app.asar 里，这边解析不到（会 ERR_MODULE_NOT_FOUND）。
//    所以消息自己用 node:crypto 的 randomUUID 造。

import { randomUUID } from 'node:crypto'
import { 情绪, 七维键, 夹紧, 心情每格 } from './量表.mjs'
import { 归一理由, 房间, 记一条 } from './状态.mjs'
import { 判模型的去处 } from './轮次.mjs'

