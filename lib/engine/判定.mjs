/**
 * 把模型那段回包读成一个增量。
 * 容错：模型可能包 markdown、前后带杂字、写到一半被截断 —— 能救就救，救不了返回 null。
 *
 * @returns { moodDelta, dims, reason, confidence } | null
 */
export function 解析判定(文本, 对方 = '对方', 诊断 = () => {}) {
  const 原文 = String(文本 || '').trim()
  if (!原文) return null

  let 对象 = null
  const 起 = 原文.indexOf('{')
  const 止 = 原文.lastIndexOf('}')
  if (起 >= 0 && 止 > 起) {
    try { 对象 = JSON.parse(原文.slice(起, 止 + 1)) } catch (e) { /* 截断了，下面再试一次整段 */ }
  }
  if (!对象) {
    try { 对象 = JSON.parse(原文) } catch (e) { /* 还是不行就认了 */ }
  }
  if (!对象 || typeof 对象 !== 'object') return null

  // ⚠️ 口径跟以前一模一样：Number.isFinite(Number(x)) 才算"给了"。
  //    undefined → 70（漏字段不该把整次注入关掉，但留一条日志）；
  //    null → 0（模型明确说了"不知道"，那就当没底，宁可不进她的嘴）。
  const 有可信度 = Number.isFinite(Number(对象.confidence))
  const 增量 = {
    moodDelta: 夹紧(Math.round(Number(对象.moodDelta) || 0), -10, 10),
    dims: Object.fromEntries(七维键.map((键) => [键, 0])),
    reason: 归一理由(对象.reason, 对方).slice(0, 120),
    confidence: 有可信度 ? 夹紧(Math.round(Number(对象.confidence)), 0, 100) : 70,
  }
  if (!有可信度) 诊断('判断没给 confidence，按 70 算')

  if (对象.dims && typeof 对象.dims === 'object') {
    for (const 键 of 七维键) 增量.dims[键] = 夹紧(Math.round(Number(对象.dims[键]) || 0), -10, 10)
  }
  return 增量
}

