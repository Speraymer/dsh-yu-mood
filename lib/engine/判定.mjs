/**
 * 跑一轮判断。
 * @param 大模型  ctx.llm
 * @param agent   当前会话的 agent（取默认模型、取会话上下文用）
 * @param 对方话  这一轮对方说的话
 * @param 己方话  这一轮她自己说的话
 * @param 口径    '' 正常聊 / 'work' 定时任务 / 'talk' 自己搭话
 * @param 称呼    { self, owner, aliases, judgeProvider, judgeModel }
 * @returns 增量 | null（拿不到模型、调用失败、解析失败都是 null）
 */
export async function 判一轮({ 大模型, agent, 对方话, 己方话, 口径 = '', 称呼 = {}, 诊断 = () => {} }) {
  const 对方 = String(称呼.owner || '对方')
  const 目标 = 判模型的去处(称呼, agent)
  if (!目标) {
    诊断('拿不到模型，跳过判断')
    return null
  }

  let 系统 = 判断提示词({ 自己: String(称呼.self || '伙伴'), 对方, 别名: String(称呼.aliases || '') })
  if (口径 === 'work') 系统 += 干活轮补充({ 对方 })
  else if (口径 === 'talk') 系统 += 搭话轮补充({ 对方 })
  const 用户话 = 拼用户话({ 对方话, 己方话, 口径, 对方 })

  const 消息 = [{
    role: 'user',
    id: randomUUID(),
    content: [{ type: 'text', text: 用户话 }],
    source: { kind: 'plugin', plugin: 'dsh-feiyu-mood' },
  }]

  let 输出 = ''
  const 分片计数 = {}
  try {
    for await (const 块 of 大模型.stream({
      provider: 目标.provider,
      model: 目标.model,
      system: 系统,
      messages: 消息,
      // ⚠️ 400 太小：reason 是中文口语，一长就切在 JSON 中间 ⇒ 整轮白判。
      //    maxTokens 只是上限，按实际吐出来的算，调大不花钱。
      maxTokens: 1000,
      temperature: 0.2,
    })) {
      if (!块) continue
      分片计数[块.type] = (分片计数[块.type] || 0) + 1
      if (块.type === 'text-delta') 输出 += 块.text
      if (块.type === 'finish' && 块.reason && 块.reason.kind === 'error') {
        const 因 = (块.reason.failure && 块.reason.failure.message) || JSON.stringify(块.reason)
        诊断('判断 finish error：' + 因)
        return null
      }
    }
  } catch (e) {
    诊断('判断调用失败：' + (e && e.message))
    return null
  }

  const 增量 = 解析判定(输出, 对方, 诊断)
  if (!增量) {
    // 空输出和"写到一半断了"是两回事：空输出多半是思考把预算吃光了，截断是 maxTokens 不够
    if (!String(输出 || '').trim()) 诊断('判断返回空（分片类型：' + JSON.stringify(分片计数) + '）')
    else 诊断('判断输出解析失败：' + String(输出 || '').slice(0, 200))
  }
  return 增量
}

